-- =====================================================================
--  آکادمی ریاضی استاد اعلایی‌نسب · Database schema
--  PostgreSQL 13+ (tested target: Render Postgres 14–17)  ·  UTF-8 (full Persian + emoji support)
--
--  Idempotent: safe to run many times (CREATE ... IF NOT EXISTS, seed rows use ON CONFLICT DO NOTHING).
--  Run:   npm run db:init                      (uses DATABASE_URL)
--     or: psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f database/schema.sql
--  The database itself is created by Render (no CREATE DATABASE / USE here).
--
--  MySQL -> PostgreSQL type map used below
--    TINYINT / SMALLINT      -> SMALLINT          TINYINT(1)            -> BOOLEAN
--    INT UNSIGNED            -> INTEGER + CHECK (>= 0)
--    BIGINT UNSIGNED AUTO_INCREMENT -> BIGINT GENERATED BY DEFAULT AS IDENTITY
--    ENUM(...)               -> native ENUM type   JSON                  -> JSONB
--    TIMESTAMP / DATETIME    -> TIMESTAMPTZ (stored as UTC instants, like mysql2 timezone:"Z")
--    ON UPDATE CURRENT_TIMESTAMP -> BEFORE UPDATE trigger
-- =====================================================================
BEGIN;

-- ---------- enum types (CREATE TYPE has no IF NOT EXISTS) ----------
DO $$ BEGIN CREATE TYPE admin_role     AS ENUM ('manager','admin','support'); EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN CREATE TYPE order_status   AS ENUM ('pending','approved','rejected'); EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN CREATE TYPE ticket_status  AS ENUM ('open','closed'); EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN CREATE TYPE message_sender AS ENUM ('student','admin'); EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN CREATE TYPE ai_role        AS ENUM ('user','assistant'); EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- ---------- "ON UPDATE CURRENT_TIMESTAMP" emulation ----------
-- MySQL only touches the column when the row really changes; so do these triggers.
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF NEW IS DISTINCT FROM OLD THEN NEW.updated_at := NOW(); END IF;
  RETURN NEW;
END $fn$;

CREATE OR REPLACE FUNCTION set_last_seen() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF NEW IS DISTINCT FROM OLD THEN NEW.last_seen := NOW(); END IF;
  RETURN NEW;
END $fn$;

-- ---------- site settings (key/value JSON) ----------
CREATE TABLE IF NOT EXISTS settings (
  "key"        VARCHAR(64)  NOT NULL PRIMARY KEY,
  "value"      JSONB        NOT NULL,
  updated_at   TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- ---------- admins / managers / support ----------
CREATE TABLE IF NOT EXISTS admins (
  id            VARCHAR(32)  NOT NULL PRIMARY KEY,
  name          VARCHAR(120) NOT NULL,
  username      VARCHAR(64)  NULL,
  password_hash VARCHAR(100) NULL,
  role          admin_role   NOT NULL DEFAULT 'admin',
  active        BOOLEAN      NOT NULL DEFAULT TRUE,
  last_login_at TIMESTAMPTZ  NULL,
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
-- MySQL's utf8mb4_unicode_ci made UNIQUE(username) and the login lookup case-insensitive; keep that behaviour.
CREATE UNIQUE INDEX IF NOT EXISTS uq_admins_username ON admins (lower(username));

-- ---------- students ----------
CREATE TABLE IF NOT EXISTS students (
  id          VARCHAR(32)  NOT NULL PRIMARY KEY,
  name        VARCHAR(120) NOT NULL,
  phone       VARCHAR(20)  NOT NULL,
  grade       SMALLINT     NOT NULL DEFAULT 7,
  bio         VARCHAR(500) NOT NULL DEFAULT '',
  ip          VARCHAR(45)  NULL,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_students_phone ON students (phone);
CREATE INDEX IF NOT EXISTS idx_students_grade ON students (grade);

-- ---------- packages & videos ----------
CREATE TABLE IF NOT EXISTS packages (
  id          VARCHAR(32)  NOT NULL PRIMARY KEY,
  grade       SMALLINT     NOT NULL,
  title       VARCHAR(200) NOT NULL,
  description TEXT         NOT NULL,
  price       INTEGER      NOT NULL DEFAULT 0 CHECK (price >= 0),   -- Toman
  pay_link    VARCHAR(500) NULL,
  hue         SMALLINT     NOT NULL DEFAULT 180,
  sort_order  INTEGER      NOT NULL DEFAULT 0,
  active      BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_packages_grade ON packages (grade);

CREATE TABLE IF NOT EXISTS videos (
  id          VARCHAR(32)  NOT NULL PRIMARY KEY,
  package_id  VARCHAR(32)  NOT NULL REFERENCES packages(id) ON DELETE CASCADE,
  title       VARCHAR(200) NOT NULL,
  duration    SMALLINT     NOT NULL DEFAULT 0,           -- minutes
  src         VARCHAR(1000) NULL,                        -- URL of the video file / stream
  sort_order  INTEGER      NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_videos_pkg ON videos (package_id, sort_order);

-- which student owns which package
CREATE TABLE IF NOT EXISTS enrollments (
  student_id  VARCHAR(32) NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  package_id  VARCHAR(32) NOT NULL REFERENCES packages(id) ON DELETE CASCADE,
  granted_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (student_id, package_id)
);
-- InnoDB indexed every foreign-key column automatically; PostgreSQL does not, so add them explicitly.
CREATE INDEX IF NOT EXISTS idx_enrollments_package ON enrollments (package_id);

-- ---------- discount codes & orders ----------
CREATE TABLE IF NOT EXISTS discount_codes (
  code        VARCHAR(40)  NOT NULL PRIMARY KEY,
  percent     SMALLINT     NOT NULL CHECK (percent BETWEEN 0 AND 255),
  active      BOOLEAN      NOT NULL DEFAULT TRUE,
  uses        INTEGER      NOT NULL DEFAULT 0   CHECK (uses >= 0),
  max_uses    INTEGER      NOT NULL DEFAULT 100 CHECK (max_uses >= 0),
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS orders (
  id          VARCHAR(32)  NOT NULL PRIMARY KEY,
  student_id  VARCHAR(32)  NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  package_id  VARCHAR(32)  NOT NULL REFERENCES packages(id) ON DELETE CASCADE,
  price       INTEGER      NOT NULL CHECK (price >= 0),  -- final price (Toman), computed on server
  code        VARCHAR(40)  NULL,
  status      order_status NOT NULL DEFAULT 'pending',
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  reviewed_by VARCHAR(32)  NULL,
  reviewed_at TIMESTAMPTZ  NULL
);
CREATE INDEX IF NOT EXISTS idx_orders_status  ON orders (status, created_at);
CREATE INDEX IF NOT EXISTS idx_orders_student ON orders (student_id);
CREATE INDEX IF NOT EXISTS idx_orders_package ON orders (package_id);

-- ---------- support tickets ----------
CREATE TABLE IF NOT EXISTS tickets (
  id          VARCHAR(32)   NOT NULL PRIMARY KEY,
  student_id  VARCHAR(32)   NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  subject     VARCHAR(200)  NOT NULL,
  status      ticket_status NOT NULL DEFAULT 'open',
  created_at  TIMESTAMPTZ   NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_tickets_status  ON tickets (status);
CREATE INDEX IF NOT EXISTS idx_tickets_student ON tickets (student_id);

CREATE TABLE IF NOT EXISTS ticket_messages (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id   VARCHAR(32)    NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  sender      message_sender NOT NULL,
  body        TEXT           NOT NULL,
  created_at  TIMESTAMPTZ    NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_ticket_messages_ticket ON ticket_messages (ticket_id, created_at);

-- ---------- ask the teacher ----------
CREATE TABLE IF NOT EXISTS questions (
  id          VARCHAR(32)  NOT NULL PRIMARY KEY,
  student_id  VARCHAR(32)  NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  body        TEXT         NOT NULL,
  answer      TEXT         NULL,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  answered_at TIMESTAMPTZ  NULL
);
CREATE INDEX IF NOT EXISTS idx_questions_student ON questions (student_id);

-- ---------- FAQ ----------
CREATE TABLE IF NOT EXISTS faqs (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question    VARCHAR(400) NOT NULL,
  answer      TEXT         NOT NULL,
  sort_order  INTEGER      NOT NULL DEFAULT 0
);

-- ---------- IP firewall ----------
CREATE TABLE IF NOT EXISTS ip_firewall (
  ip          VARCHAR(45)  NOT NULL PRIMARY KEY,
  who         VARCHAR(120) NOT NULL DEFAULT 'ناشناس',
  city        VARCHAR(80)  NOT NULL DEFAULT 'نامشخص',
  hits        INTEGER      NOT NULL DEFAULT 0 CHECK (hits >= 0),
  blocked     BOOLEAN      NOT NULL DEFAULT FALSE,
  last_seen   TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_ip_firewall_blocked ON ip_firewall (blocked);

-- ---------- AI assistant ----------
CREATE TABLE IF NOT EXISTS ai_settings (
  id          SMALLINT     NOT NULL PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  config      JSONB        NOT NULL,                     -- name, avatar, colors, provider, model, prompt...
  api_key_enc TEXT         NULL,                         -- AES-256-GCM encrypted, never sent to browsers
  updated_by  VARCHAR(32)  NULL,
  updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS ai_conversations (
  id          VARCHAR(64)  NOT NULL PRIMARY KEY,         -- browser session id
  ip          VARCHAR(45)  NULL,
  page        VARCHAR(200) NULL,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS ai_messages (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id VARCHAR(64) NOT NULL REFERENCES ai_conversations(id) ON DELETE CASCADE,
  role            ai_role     NOT NULL,
  content         TEXT        NOT NULL,
  tokens          INTEGER     NULL,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_ai_messages_conv    ON ai_messages (conversation_id, created_at);
CREATE INDEX IF NOT EXISTS idx_ai_messages_created ON ai_messages (created_at);

-- ---------- audit log ----------
CREATE TABLE IF NOT EXISTS audit_log (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id    VARCHAR(32)  NULL,
  action      VARCHAR(80)  NOT NULL,
  detail      JSONB        NULL,
  ip          VARCHAR(45)  NULL,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_audit_log_created ON audit_log (created_at);

-- ---------- updated_at / last_seen triggers ----------
DROP TRIGGER IF EXISTS trg_settings_updated_at          ON settings;
CREATE TRIGGER trg_settings_updated_at          BEFORE UPDATE ON settings          FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS trg_packages_updated_at          ON packages;
CREATE TRIGGER trg_packages_updated_at          BEFORE UPDATE ON packages          FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS trg_ai_settings_updated_at       ON ai_settings;
CREATE TRIGGER trg_ai_settings_updated_at       BEFORE UPDATE ON ai_settings       FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS trg_ai_conversations_updated_at  ON ai_conversations;
CREATE TRIGGER trg_ai_conversations_updated_at  BEFORE UPDATE ON ai_conversations  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS trg_ip_firewall_last_seen        ON ip_firewall;
CREATE TRIGGER trg_ip_firewall_last_seen        BEFORE UPDATE ON ip_firewall       FOR EACH ROW EXECUTE FUNCTION set_last_seen();

